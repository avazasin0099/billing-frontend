/**
 * Standard line icon for a product category, used when an item has no real photo.
 * Matching is keyword-based on the category name (case-insensitive); first match wins.
 * Falls back to a neutral Package icon — never a fake coloured tile or letter.
 */
const RULES: Array<[RegExp, LucideIcon]> = [
  [/rx|prescription|otc|medicine|pharma|tablet(?!s & )|ayurved/, Pill],
  [/surgical|first aid|device|equipment|wellness|supplement/, Stethoscope],
  [/baby|kids/, Baby],
  [/dairy|milk|curd|paneer/, Milk],
  [/egg/, Egg],
  [/tea|coffee/, Coffee],
  [/beverage|drink|juice|soda/, CupSoda],
  [/beer|wine|liquor/, Beer],
  [/biscuit|bakery|cookie/, Cookie],
  [/cake|pastr|dessert/, CakeSlice],
  [/sweet|mithai|chocolate|candy/, Candy],
  [/ice cream|frozen/, IceCreamCone],
  [/snack|namkeen|chips/, Popcorn],
  [/rice|flour|atta|grain|staple|pulse|dal|bread/, Wheat],
  [/oil|ghee/, Droplet],
  [/spice|masala/, Leaf],
  [/fruit|vegetable|produce|dry fruit/, Apple],
  [/starter|main course|biryani|chinese|south indian|combo|add-on|food/, UtensilsCrossed],
  [/soup|ready to eat|packaged/, Soup],
  [/salad|organic/, Salad],
  [/clean|household|detergent/, SprayCan],
  [/bath|body|soap|personal care/, Bath],
  [/skin|hair|makeup|fragrance|groom|beauty|cosmetic|brush/, Sparkles],
  [/footwear|shoe/, Footprints],
  [/jewel|gold|silver/, Gem],
  [/winter|woolen/, Snowflake],
  [/wear|apparel|fashion|cloth|ethnic|innerwear|garment/, Shirt],
  [/bag|accessor/, ShoppingBag],
  [/mobile|phone|tablet/, Smartphone],
  [/laptop|computer/, Laptop],
  [/tv|audio|speaker/, Tv],
  [/headphone|earphone/, Headphones],
  [/camera/, Camera],
  [/cable|charger/, Cable],
  [/batter|power/, Battery],
  [/light|lamp|bulb/, Lamp],
  [/appliance|kitchen|fridge|refrigerator/, Refrigerator],
  [/electric|smart device|switch/, Plug],
  [/tool|fastener|hardware|plumb|sanitary|safety|building/, Wrench],
  [/paint|adhesive|art|craft/, Paintbrush],
  [/notebook|pen|pencil|office|school|printing|paper|stationery/, Pencil],
  [/book/, BookOpen],
  [/gift/, Gift],
  [/hammer/, Hammer],
];

export function categoryIcon(category?: string | null): LucideIcon {
  const name = (category || '').toLowerCase();
  if (!name) return Package;
  for (const [pattern, Icon] of RULES) {
    if (pattern.test(name)) return Icon;
  }
  return Package;
}
